import { AnalysisResult, NextStepItem } from '../types/clarity';

/**
 * Format analysis result into clean, publication-ready GitHub Flavored Markdown
 */
export function formatMarkdownReport(result: AnalysisResult, steps: NextStepItem[]): string {
  const completedCount = steps.filter((s) => s.completed).length;
  const progressPct = steps.length > 0 ? Math.round((completedCount / steps.length) * 100) : 0;

  return `# ClarityLens Multimodal Visual Breakdown

> **Mode**: \`${result.mode}\` | **Model**: \`${result.model_used}\` | **Timestamp**: ${new Date(result.timestamp).toLocaleString()}  
> **Status**: ${result.isDemoSample ? 'Demonstration Sample' : 'Live Multimodal Inference'} ${result.latencyMs ? `(${result.latencyMs}ms)` : ''}

---

## 1. 👁️ What I See
${result.image_summary}

---

## 2. 🔍 The Important Details
${result.important_details.map((detail) => `- ${detail}`).join('\n')}

---

## 3. 💡 What It Means
${result.explanation}

---

## 4. 🚀 Actionable Next Steps (${completedCount}/${steps.length} completed — ${progressPct}%)
${steps
  .map(
    (step, idx) =>
      `- [${step.completed ? 'x' : ' '}] **${idx + 1}. [${step.priority.toUpperCase()}] ${step.title}**  \n  ${step.description}${
        step.codeSnippet ? `\n\n  \`\`\`bash\n  ${step.codeSnippet}\n  \`\`\`` : ''
      }`
  )
  .join('\n\n')}

---

## 5. ⚠️ Things to Verify (Uncertainty Boundaries)
${
  result.uncertainties.length > 0
    ? result.uncertainties.map((u) => `- ❓ ${u}`).join('\n')
    : '_No ambiguous or cut-off elements detected in image._'
}

---

## 💬 Suggested Follow-Up
> "${result.follow_up_question}"

---
_Generated by [ClarityLens](https://github.com/your-username/claritylens) — Powered by Google Gemma 4 (\`${result.model_used}\`)_
`;
}

/**
 * Format analysis result into plain text report
 */
export function formatPlainTextReport(result: AnalysisResult, steps: NextStepItem[]): string {
  const completedCount = steps.filter((s) => s.completed).length;

  return `==================================================
CLARITYLENS MULTIMODAL ANALYSIS REPORT
==================================================
Model: ${result.model_used}
Mode: ${result.mode}
Timestamp: ${result.timestamp}
Demo Sample: ${result.isDemoSample ? 'YES (Pre-seeded Demonstration)' : 'NO (Live Inference)'}
${result.latencyMs ? `Latency: ${result.latencyMs}ms\n` : ''}==================================================

1. WHAT I SEE:
${result.image_summary}

2. IMPORTANT DETAILS:
${result.important_details.map((d) => `  - ${d}`).join('\n')}

3. WHAT IT MEANS:
${result.explanation}

4. YOUR NEXT STEPS (${completedCount}/${steps.length} completed):
${steps
  .map(
    (s, i) =>
      `  [${s.completed ? 'X' : ' '}] ${i + 1}. [${s.priority.toUpperCase()}] ${s.title}\n     ${s.description}${
        s.codeSnippet ? `\n     Command: ${s.codeSnippet}` : ''
      }`
  )
  .join('\n')}

5. THINGS TO VERIFY:
${result.uncertainties.length > 0 ? result.uncertainties.map((u) => `  - ${u}`).join('\n') : '  - None detected'}

FOLLOW-UP RECOMMENDATION:
"${result.follow_up_question}"

==================================================
Generated by ClarityLens — Powered by Gemma 4 (${result.model_used})
`;
}

/**
 * Download a file in browser
 */
export function triggerFileDownload(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
