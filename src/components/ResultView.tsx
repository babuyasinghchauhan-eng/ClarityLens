import React, { useState } from 'react';
import {
  Copy,
  Check,
  Download,
  RotateCcw,
  Eye,
  List,
  Cpu,
  CheckSquare,
  AlertCircle,
  HelpCircle,
  Share2,
  Sparkles
} from 'lucide-react';
import { AnalysisResult, NextStepItem } from '../types/clarity';

interface ResultViewProps {
  result: AnalysisResult;
  onReset: () => void;
  onAnalyzeAnother: () => void;
}

export const ResultView: React.FC<ResultViewProps> = ({
  result,
  onReset,
  onAnalyzeAnother,
}) => {
  const [steps, setSteps] = useState<NextStepItem[]>(result.next_steps);
  const [copiedSection, setCopiedSection] = useState<string | null>(null);

  const toggleStep = (id: string) => {
    setSteps((prev) =>
      prev.map((step) =>
        step.id === id ? { ...step, completed: !step.completed } : step
      )
    );
  };

  const handleCopy = (text: string, sectionKey: string) => {
    navigator.clipboard.writeText(text);
    setCopiedSection(sectionKey);
    setTimeout(() => {
      setCopiedSection((current) => (current === sectionKey ? null : current));
    }, 2000);
  };

  const formatFullTextReport = (): string => {
    return `CLARITYLENS MULTIMODAL ANALYSIS REPORT
Model: ${result.model_used}
Mode: ${result.mode}
Timestamp: ${result.timestamp}
Demo Sample: ${result.isDemoSample ? 'YES (Sample Demonstration)' : 'NO (Live Gemma 4 Inference)'}
==================================================

1. WHAT I SEE:
${result.image_summary}

2. IMPORTANT DETAILS:
${result.important_details.map((d, i) => `  - ${d}`).join('\n')}

3. WHAT IT MEANS:
${result.explanation}

4. YOUR NEXT STEPS:
${steps
  .map(
    (s, i) =>
      `  [${s.completed ? 'X' : ' '}] ${i + 1}. [${s.priority.toUpperCase()}] ${s.title}\n     ${s.description}`
  )
  .join('\n')}

5. THINGS TO VERIFY:
${result.uncertainties.map((u) => `  - ${u}`).join('\n')}

FOLLOW-UP RECOMMENDATION:
${result.follow_up_question}

==================================================
Generated by ClarityLens — Powered by Gemma 4 (gemma-4-26b-a4b-it)`;
  };

  const handleDownload = () => {
    const reportText = formatFullTextReport();
    const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `claritylens-analysis-${result.mode}-${Date.now()}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-5 sm:p-6 shadow-xs flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 text-xs font-semibold text-[#6742F5] uppercase tracking-wide">
            <span>ANALYSIS COMPLETE</span>
            <span aria-hidden="true">·</span>
            <span className="font-mono text-[#706D7A]">{result.model_used}</span>
          </div>
          <h2 className="text-xl sm:text-2xl font-bold text-[#17151F] mt-1">
            Gemma 4 Multimodal Visual Breakdown
          </h2>
          {result.isDemoSample && (
            <div className="mt-2 inline-flex items-center gap-1.5 px-2.5 py-1 rounded-md bg-[#FFF1EE] text-[#FF8066] text-xs font-semibold">
              <Sparkles className="w-3.5 h-3.5" />
              <span>Sample Analysis (Pre-seeded Demonstration)</span>
            </div>
          )}
        </div>

        {/* Global Result Actions */}
        <div className="flex flex-wrap items-center gap-2.5">
          <button
            onClick={() => handleCopy(formatFullTextReport(), 'full')}
            className="px-3.5 py-2 text-xs font-semibold text-[#17151F] bg-[#F7F6FA] hover:bg-[#F0ECFF] hover:text-[#3921A8] border border-[#17151F]/10 rounded-xl transition-colors flex items-center gap-1.5 cursor-pointer"
            title="Copy entire structured report"
          >
            {copiedSection === 'full' ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700">Copied Full Report!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-[#706D7A]" />
                <span>Copy Full Result</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownload}
            className="px-3.5 py-2 text-xs font-semibold text-white bg-[#6742F5] hover:bg-[#3921A8] rounded-xl shadow-xs transition-colors flex items-center gap-1.5 cursor-pointer"
            title="Download plain-text report"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Report (.txt)</span>
          </button>

          <button
            onClick={onReset}
            className="p-2 text-[#706D7A] hover:text-[#17151F] hover:bg-[#F7F6FA] border border-[#17151F]/10 rounded-xl transition-colors cursor-pointer"
            title="Reset workspace"
          >
            <RotateCcw className="w-4 h-4" />
          </button>
        </div>
      </div>

      {/* Section 1: What I See */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-6 space-y-3 shadow-xs">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#F0ECFF] flex items-center justify-center text-[#6742F5]">
              <Eye className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-[#17151F]">1. What I See</h3>
          </div>
          <button
            onClick={() => handleCopy(result.image_summary, 'summary')}
            className="text-xs text-[#706D7A] hover:text-[#6742F5] flex items-center gap-1 cursor-pointer"
          >
            {copiedSection === 'summary' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
            <span>{copiedSection === 'summary' ? 'Copied' : 'Copy'}</span>
          </button>
        </div>
        <p className="text-sm text-[#17151F] leading-relaxed pl-10">
          {result.image_summary}
        </p>
      </div>

      {/* Section 2: Important Details */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-6 space-y-3 shadow-xs">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#FFF1EE] flex items-center justify-center text-[#FF8066]">
              <List className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-[#17151F]">2. The Important Details</h3>
          </div>
          <button
            onClick={() =>
              handleCopy(
                result.important_details.map((d) => `• ${d}`).join('\n'),
                'details'
              )
            }
            className="text-xs text-[#706D7A] hover:text-[#6742F5] flex items-center gap-1 cursor-pointer"
          >
            {copiedSection === 'details' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
            <span>{copiedSection === 'details' ? 'Copied' : 'Copy'}</span>
          </button>
        </div>
        <ul className="pl-10 space-y-2 text-sm text-[#17151F]">
          {result.important_details.map((item, idx) => (
            <li key={idx} className="flex items-start gap-2.5">
              <span className="w-1.5 h-1.5 rounded-full bg-[#6742F5] mt-2 shrink-0" />
              <span className="leading-relaxed">{item}</span>
            </li>
          ))}
        </ul>
      </div>

      {/* Section 3: What It Means */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-6 space-y-3 shadow-xs">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#F0ECFF] flex items-center justify-center text-[#3921A8]">
              <Cpu className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-[#17151F]">3. What It Means</h3>
          </div>
          <button
            onClick={() => handleCopy(result.explanation, 'explanation')}
            className="text-xs text-[#706D7A] hover:text-[#6742F5] flex items-center gap-1 cursor-pointer"
          >
            {copiedSection === 'explanation' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
            <span>{copiedSection === 'explanation' ? 'Copied' : 'Copy'}</span>
          </button>
        </div>
        <p className="text-sm text-[#17151F] leading-relaxed pl-10">
          {result.explanation}
        </p>
      </div>

      {/* Section 4: Your Next Steps (Checkable List) */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-6 space-y-4 shadow-xs">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#ECFDF5] flex items-center justify-center text-[#059669]">
              <CheckSquare className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-[#17151F]">4. Your Next Steps</h3>
          </div>
          <div className="flex items-center gap-3">
            <span className="text-xs text-[#706D7A]">
              {steps.filter((s) => s.completed).length}/{steps.length} completed
            </span>
            <button
              onClick={() =>
                handleCopy(
                  steps
                    .map(
                      (s, i) =>
                        `${i + 1}. [${s.priority.toUpperCase()}] ${s.title}: ${s.description}`
                    )
                    .join('\n'),
                  'steps'
                )
              }
              className="text-xs text-[#706D7A] hover:text-[#6742F5] flex items-center gap-1 cursor-pointer"
            >
              {copiedSection === 'steps' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
              <span>{copiedSection === 'steps' ? 'Copied' : 'Copy'}</span>
            </button>
          </div>
        </div>

        <div className="pl-10 space-y-3">
          {steps.map((step) => {
            const isHigh = step.priority === 'high';
            const isMed = step.priority === 'medium';
            return (
              <div
                key={step.id}
                onClick={() => toggleStep(step.id)}
                className={`p-3.5 rounded-xl border transition-all cursor-pointer flex items-start gap-3.5 ${
                  step.completed
                    ? 'bg-[#F7F6FA] border-[#17151F]/5 opacity-60'
                    : 'bg-white border-[#17151F]/10 hover:border-[#6742F5]/40'
                }`}
              >
                <input
                  type="checkbox"
                  checked={!!step.completed}
                  onChange={() => toggleStep(step.id)}
                  className="w-4 h-4 mt-1 rounded border-[#706D7A] text-[#6742F5] focus:ring-[#6742F5] cursor-pointer"
                  onClick={(e) => e.stopPropagation()}
                />
                <div className="flex-1 space-y-1">
                  <div className="flex items-center gap-2">
                    <span
                      className={`text-sm font-semibold ${
                        step.completed ? 'line-through text-[#706D7A]' : 'text-[#17151F]'
                      }`}
                    >
                      {step.title}
                    </span>
                    <span
                      className={`text-[10px] font-bold uppercase tracking-wider px-1.5 py-0.5 rounded ${
                        isHigh
                          ? 'bg-[#FFF1EE] text-[#FF8066]'
                          : isMed
                          ? 'bg-[#F0ECFF] text-[#6742F5]'
                          : 'bg-gray-100 text-gray-600'
                      }`}
                    >
                      {step.priority}
                    </span>
                  </div>
                  <p
                    className={`text-xs leading-relaxed ${
                      step.completed ? 'text-[#706D7A]' : 'text-[#706D7A]'
                    }`}
                  >
                    {step.description}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {/* Section 5: Things to Verify */}
      <div className="bg-white rounded-2xl border border-[#17151F]/10 p-6 space-y-3 shadow-xs">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#FFFBEB] flex items-center justify-center text-[#D97706]">
              <AlertCircle className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-[#17151F]">5. Things to Verify</h3>
          </div>
          <button
            onClick={() =>
              handleCopy(
                result.uncertainties.map((u) => `• ${u}`).join('\n'),
                'uncertainties'
              )
            }
            className="text-xs text-[#706D7A] hover:text-[#6742F5] flex items-center gap-1 cursor-pointer"
          >
            {copiedSection === 'uncertainties' ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
            <span>{copiedSection === 'uncertainties' ? 'Copied' : 'Copy'}</span>
          </button>
        </div>
        <div className="pl-10 space-y-2">
          {result.uncertainties.length > 0 ? (
            <ul className="space-y-2 text-sm text-[#706D7A]">
              {result.uncertainties.map((item, idx) => (
                <li key={idx} className="flex items-start gap-2.5">
                  <span className="w-1.5 h-1.5 rounded-full bg-[#D97706] mt-2 shrink-0" />
                  <span className="leading-relaxed">{item}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-sm text-[#706D7A]">
              No ambiguous or missing visual elements detected in the provided image.
            </p>
          )}
        </div>
      </div>

      {/* Follow-up question callout */}
      {result.follow_up_question && (
        <div className="bg-[#F0ECFF]/60 rounded-2xl border border-[#6742F5]/20 p-5 flex items-start gap-3.5">
          <HelpCircle className="w-5 h-5 text-[#6742F5] mt-0.5 shrink-0" />
          <div className="space-y-1">
            <div className="text-xs font-bold text-[#3921A8] uppercase tracking-wide">
              Suggested Follow-up
            </div>
            <p className="text-sm text-[#17151F] font-medium">
              "{result.follow_up_question}"
            </p>
          </div>
        </div>
      )}

      {/* Bottom workspace actions */}
      <div className="pt-2 flex flex-wrap items-center justify-between gap-4">
        <button
          onClick={onAnalyzeAnother}
          className="px-5 py-2.5 text-sm font-semibold text-white bg-[#6742F5] hover:bg-[#3921A8] rounded-xl shadow-xs transition-colors cursor-pointer"
        >
          Analyze Another Image
        </button>

        <button
          onClick={onReset}
          className="px-4 py-2 text-sm font-medium text-[#706D7A] hover:text-[#17151F] cursor-pointer"
        >
          Clear Workspace
        </button>
      </div>
    </div>
  );
};
